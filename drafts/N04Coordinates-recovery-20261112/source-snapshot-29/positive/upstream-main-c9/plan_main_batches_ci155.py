def cost(modules):
    return sum(costs[m]['budget_added'] for m in modules)


def closure(modules):
    seen = set()
    def visit(m):
        if m in seen:
            return
        seen.add(m)
        for dep in selected[m]['imports']:
            if dep in selected:
                visit(dep)
    for m in modules:
        visit(m)
    return seen


