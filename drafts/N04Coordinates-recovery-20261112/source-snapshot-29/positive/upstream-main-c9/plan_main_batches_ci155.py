def cache_bytes(b):
    p = CACHE / (blob(b) + '.txt')
    if p.exists():
        assert p.read_bytes() == b
    else:
        p.write_bytes(b)
    return p


def git_numstat(a, b):
    pa, pb = cache_bytes(a), cache_bytes(b)
    q = subprocess.run(['git', '-C', str(REPO), 'diff', '--no-index', '--numstat',
                        '--no-ext-diff', '--', str(pa), str(pb)],
                       text=True, stdout=subprocess.PIPE)
    assert q.returncode in (0, 1)
    if not q.stdout.strip():
        return (0, 0)
    line, = q.stdout.splitlines()
    x, y, _ = line.split('\t', 2)
    return int(x), int(y)


