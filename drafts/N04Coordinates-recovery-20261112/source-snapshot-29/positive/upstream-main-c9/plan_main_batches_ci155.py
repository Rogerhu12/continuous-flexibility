def blob(b):
    return hashlib.sha1(b'blob ' + str(len(b)).encode() + b'\0' + b).hexdigest()


def fp(p):
    b = Path(p).read_bytes()
    return dict(path=str(p), blob=blob(b), sha256=hashlib.sha256(b).hexdigest(), lines=len(b.splitlines()))


def write_new(p, obj):
    assert not p.exists(), p
    p.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + '\n')
    return fp(p)


