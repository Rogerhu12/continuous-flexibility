def fill_safe(group):
    for m in order:
        if m not in safe_new or m in done or m in group:
            continue
        add = {m}
        if m == spatial:
            add.add(mixed)
        if cost(group | add) > CAP:
            continue
        required_updates = (closure(add) & changes) - (done | group | add)
        if required_updates:
            continue
        group.update(add)
    return group


