"""Resolve the expected merge conflicts of a line branch into main.

The root import is regenerated by scripts/gen_root.py; docs/STATUS.md keeps
our side (the lead rewrites the ledger after the merge). Any other conflicted
file is an error: it must be resolved by hand.
"""
import subprocess
import pathlib


def show(stage: int, f: str) -> str:
    return subprocess.run(['git', 'show', f':{stage}:{f}'], capture_output=True,
                          text=True, encoding='utf-8').stdout


files = subprocess.run(['git', 'diff', '--name-only', '--diff-filter=U'],
                       capture_output=True, text=True).stdout.split()
for f in files:
    p = pathlib.Path(f)
    if f in ('src/ContinuousFlexibility.lean', 'docs/STATUS.md'):
        # The root import is regenerated below; the ledger keeps our side and is
        # rewritten by the lead after the merge.
        subprocess.run(['git', 'checkout', '--ours', '--', f], check=True)
    else:
        raise SystemExit('unexpected conflict in ' + f)
    subprocess.run(['git', 'add', f], check=True)
subprocess.run(['python', '-I', 'scripts/gen_root.py'], check=True)
subprocess.run(['git', 'add', 'src/ContinuousFlexibility.lean'], check=True)
print('resolved:', ' '.join(files) if files else 'nothing')
