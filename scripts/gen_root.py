"""Generate the root import src/ContinuousFlexibility.lean.

The root imports every module under src/ContinuousFlexibility/ except the
blueprint (whose open nodes contain `sorry`; it is built through the Solution
library) and the modules listed in scripts/root_exclude.txt (unfinished files
that do not compile). CI runs this before every build; run it before building
the root library locally. Lines never edit the root by hand, so pull requests
do not conflict on it.

Usage: python3 scripts/gen_root.py [--check]
  --check  exit with status 1 if the file on disk differs from the generated one.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PKG = SRC / "ContinuousFlexibility"
OUT = SRC / "ContinuousFlexibility.lean"
EXCLUDE = ROOT / "scripts" / "root_exclude.txt"

HEADER = """-- Generated by scripts/gen_root.py. Do not edit: every module under
-- src/ContinuousFlexibility/ outside Blueprint/ is imported, minus scripts/root_exclude.txt.
"""


def modules() -> list[str]:
    excluded = set()
    if EXCLUDE.exists():
        for line in EXCLUDE.read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                excluded.add(line)
    names = []
    for path in PKG.rglob("*.lean"):
        rel = path.relative_to(SRC).with_suffix("")
        if rel.parts[1] == "Blueprint":
            continue
        name = ".".join(rel.parts)
        if name not in excluded:
            names.append(name)
    return sorted(names)


def main() -> None:
    text = HEADER + "".join(f"import {m}\n" for m in modules())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        sys.exit(0 if current == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {text.count(chr(10) + 'import ') + text.startswith('import ')} imports")


if __name__ == "__main__":
    main()
